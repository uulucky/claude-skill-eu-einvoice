"""Layered validation of e-invoices (XML or Factur-X/ZUGFeRD PDF).

Layers, in the order receiving platforms apply them:
  1. well-formed XML
  2. XSD (UBL 2.1 or CII / Factur-X schema)            -> structure
  3. CEN EN 16931 Schematron                           -> business rules BR-xx
  4. CIUS Schematron (Peppol / XRechnung)              -> national rules
  5. for PDFs: Factur-X container checks               -> attachment, XMP

An invoice is "valid" when layers 1-4 report no error/fatal findings.
Warnings are reported but do not fail.
"""

import os
import re
import tempfile
from pathlib import Path

from lxml import etree

from . import artifacts
from .hints import hint_for
from .profiles import PROFILES, detect_profile

SVRL = "http://purl.oclc.org/dsdl/svrl"
UBL_INV = "urn:oasis:names:specification:ubl:schema:xsd:Invoice-2"
UBL_CN = "urn:oasis:names:specification:ubl:schema:xsd:CreditNote-2"
CII = "urn:un:unece:uncefact:data:standard:CrossIndustryInvoice:100"

_xsd_cache = {}


def _facturx_data_dir():
    try:
        import facturx
    except ImportError:
        return None
    return Path(facturx.__file__).parent / "xsd_and_schematron"


def _xsd_for(root):
    base = _facturx_data_dir()
    if base is None:
        return None
    ns = etree.QName(root).namespace
    rel = {
        UBL_INV: "ubl-2.1/maindoc/UBL-Invoice-2.1.xsd",
        UBL_CN: "ubl-2.1/maindoc/UBL-CreditNote-2.1.xsd",
        CII: "facturx-en16931/Factur-X_EN16931.xsd",
    }.get(ns)
    if not rel:
        return None
    path = base / rel
    if rel not in _xsd_cache:
        _xsd_cache[rel] = etree.XMLSchema(etree.parse(str(path)))
    return _xsd_cache[rel]


def syntax_of(root):
    ns = etree.QName(root).namespace
    if ns in (UBL_INV, UBL_CN):
        return "ubl"
    if ns == CII:
        return "cii"
    return None


def customization_of(root):
    ram = "{urn:un:unece:uncefact:data:standard:ReusableAggregateBusinessInformationEntity:100}"
    if syntax_of(root) == "ubl":
        el = root.find("{urn:oasis:names:specification:ubl:schema:xsd:CommonBasicComponents-2}CustomizationID")
    else:
        el = root.find(f".//{ram}GuidelineSpecifiedDocumentContextParameter/{ram}ID")
    return el.text.strip() if el is not None and el.text else ""


def _pretty_location(loc):
    if not loc:
        return ""
    loc = re.sub(r"Q\{[^}]*\}", "", loc)
    loc = re.sub(r"\*:([A-Za-z]+)\[namespace-uri\(\)='[^']*'\]", r"\1", loc)
    return loc


def _parse_svrl(text, layer):
    findings = []
    root = etree.fromstring(text.encode("utf-8"))
    for tag in ("failed-assert", "successful-report"):
        for fa in root.iter(f"{{{SVRL}}}{tag}"):
            msg_el = fa.find(f"{{{SVRL}}}text")
            msg = " ".join("".join(msg_el.itertext()).split()) if msg_el is not None else ""
            flag = (fa.get("flag") or fa.get("role") or "error").lower()
            rule = fa.get("id") or ""
            if not rule:
                m = re.match(r"\[([A-Z0-9-]+)\]", msg)
                rule = m.group(1) if m else ""
            hint = hint_for(rule)
            loc = _pretty_location(fa.get("location"))
            if rule == "PEPPOL-EN16931-R008" and loc.rstrip("]1[").endswith("ApplicableHeaderTradeDelivery"):
                hint = ("Harmless here: CII requires ApplicableHeaderTradeDelivery even without delivery data. "
                        "Add 'delivery.date' (date of supply) to fill it - in Germany that date is legally required anyway.")
            findings.append({
                "layer": layer,
                "rule": rule,
                "severity": "warning" if flag in ("warning", "information", "info") else "error",
                "flag": flag,
                "message": msg,
                "location": loc,
                "hint": hint,
            })
    return findings


def _xsd_findings(tree):
    schema = _xsd_for(tree.getroot())
    if schema is None:
        return [], False
    if schema.validate(tree):
        return [], True
    out = []
    for e in schema.error_log:
        msg = re.sub(r"\{[^}]*\}", "", e.message)
        out.append({
            "layer": "xsd",
            "rule": "XSD",
            "severity": "error",
            "flag": "fatal",
            "message": f"line {e.line}: {msg}",
            "location": e.path or "",
            "hint": "Structure error: an element is missing, misspelled or out of schema order. "
                    "If the XML was generated by this skill, report it; if hand-written, compare with scripts/eu_einvoice/examples.",
        })
    return out, True


def _facturx_version():
    try:
        from importlib.metadata import version
        return version("factur-x")
    except Exception:
        return "?"


def extract_xml_from_pdf(pdf_bytes):
    try:
        from facturx import get_xml_from_pdf
    except ImportError as e:
        raise RuntimeError("factur-x is not installed: pip install -r requirements.txt") from e
    filename, xml = get_xml_from_pdf(pdf_bytes, check_xsd=False)
    return filename, xml


def _pdf_findings(pdf_bytes, xml_filename):
    out = []

    def add(sev, msg, hint=""):
        out.append({"layer": "pdf", "rule": "PDF", "severity": sev, "flag": sev, "message": msg, "location": "", "hint": hint})

    if not xml_filename:
        add("error", "no embedded invoice XML found", "Factur-X/ZUGFeRD PDFs must embed factur-x.xml (or zugferd-invoice.xml / xrechnung.xml).")
        return out
    if xml_filename not in ("factur-x.xml", "zugferd-invoice.xml", "xrechnung.xml", "ZUGFeRD-invoice.xml"):
        add("warning", f"embedded XML is named '{xml_filename}'", "Factur-X 1.0 and ZUGFeRD 2.x expect 'factur-x.xml'.")
    try:
        import io

        from pypdf import PdfReader
        r = PdfReader(io.BytesIO(pdf_bytes))
        raw = r.trailer["/Root"].get("/Metadata")
        xmp = raw.get_object().get_data().decode("utf-8", "ignore") if raw else ""
        if "pdfaid:part" not in xmp and "pdfaid:part=" not in xmp:
            add("error", "XMP metadata has no PDF/A identification (pdfaid:part)", "Factur-X requires PDF/A-3. Re-create it with `einvoice_cli.py create --profile facturx`.")
        elif not re.search(r"pdfaid:part(>|=\")3", xmp):
            add("error", "PDF declares a PDF/A part other than 3", "Factur-X requires PDF/A-3 (part 3), because only PDF/A-3 allows embedded XML.")
        if "ConformanceLevel" not in xmp:
            add("error", "XMP lacks the Factur-X extension schema (fx:ConformanceLevel)")
        if "/OutputIntents" not in r.trailer["/Root"]:
            add("error", "PDF has no OutputIntent (ICC profile)", "PDF/A requires an OutputIntent; `einvoice_cli.py create` adds an sRGB one.")
    except Exception as e:  # pragma: no cover - diagnostic only
        add("warning", f"could not inspect PDF metadata: {e}")
    add("info", "PDF/A-3 conformance of fonts/colour is not fully checked here; run veraPDF for a formal check (see references/facturx-zugferd.md).")
    return out


def validate(path_or_bytes, profile=None, layers=None, fetch=True, log=lambda *a, **k: None):
    """Validate an invoice file. Returns a result dict (see format_report)."""
    if isinstance(path_or_bytes, (str, Path)):
        data = Path(path_or_bytes).read_bytes()
        name = str(path_or_bytes)
    else:
        data, name = path_or_bytes, "<bytes>"

    findings, layers_run, skipped = [], [], []
    is_pdf = data[:5] == b"%PDF-"
    if is_pdf:
        xml_name, xml = extract_xml_from_pdf(data)
        findings += _pdf_findings(data, xml_name)
        layers_run.append("pdf")
        if not xml:
            return _result(name, None, profile, findings, layers_run, skipped)
        data = xml

    try:
        tree = etree.ElementTree(etree.fromstring(data))
    except etree.XMLSyntaxError as e:
        findings.append({"layer": "xml", "rule": "XML", "severity": "error", "flag": "fatal",
                         "message": f"not well-formed XML: {e}", "location": "", "hint": ""})
        return _result(name, None, profile, findings, layers_run, skipped)
    root = tree.getroot()
    syntax = syntax_of(root)
    if not syntax:
        findings.append({"layer": "xml", "rule": "XML", "severity": "error", "flag": "fatal",
                         "message": f"root element {root.tag} is neither UBL Invoice/CreditNote nor CII CrossIndustryInvoice",
                         "location": "", "hint": ""})
        return _result(name, syntax, profile, findings, layers_run, skipped)

    if profile is None:
        profile = "facturx" if is_pdf else detect_profile(customization_of(root), syntax)
    prof = PROFILES[profile]
    if prof["syntax"] != syntax:
        findings.append({"layer": "xml", "rule": "PROFILE", "severity": "error", "flag": "fatal",
                         "message": f"profile {profile} expects {prof['syntax'].upper()} but the document is {syntax.upper()}",
                         "location": "", "hint": "Pick the matching profile, e.g. xrechnung-cii for a CII XRechnung."})
        return _result(name, syntax, profile, findings, layers_run, skipped)

    xsd_f, ran = _xsd_findings(tree)
    findings += xsd_f
    (layers_run if ran else skipped).append("xsd")

    rule_sets = layers or prof["rules"]
    with tempfile.NamedTemporaryFile("wb", suffix=".xml", delete=False) as tmp:
        tmp.write(etree.tostring(tree, xml_declaration=True, encoding="UTF-8"))
        tmp_path = tmp.name
    try:
        for rs in rule_sets:
            if rs.startswith("facturx-"):
                # shipped inside the factur-x package (FNFE-MPE schematron incl. its code DB)
                base = _facturx_data_dir()
                xslt = base / rs / f"FACTUR-X_{rs.split('-', 1)[1].upper()}.xslt" if base else None
                if not xslt or not xslt.exists():
                    skipped.append(f"{rs} (factur-x package not installed)")
                    continue
                from .saxon import run_xslt
                findings += _parse_svrl(run_xslt(xslt, tmp_path), rs)
                layers_run.append(f"{rs}@factur-x-lib-{_facturx_version()}")
                continue
            xslt = artifacts.xslt_path(rs)
            if xslt is None and fetch:
                try:
                    xslt = artifacts.fetch(rs, log=log)
                except Exception as e:
                    skipped.append(f"{rs} (download failed: {e})")
                    continue
            if xslt is None:
                skipped.append(f"{rs} (not cached; run: einvoice_cli.py rules fetch)")
                continue
            from .saxon import run_xslt
            svrl = run_xslt(xslt, tmp_path)
            findings += _parse_svrl(svrl, rs)
            layers_run.append(f"{rs}@{artifacts.MANIFEST[rs]['version']}")
    finally:
        os.unlink(tmp_path)
    return _result(name, syntax, profile, findings, layers_run, skipped)


def _result(name, syntax, profile, findings, layers_run, skipped):
    # de-duplicate: the Factur-X schematron repeats the CEN rules, so the same
    # rule + message can arrive from two layers (with different locations)
    first_layer, uniq = {}, []
    for f in findings:
        key = (f["rule"], f["message"])
        if first_layer.setdefault(key, f["layer"]) != f["layer"]:
            continue
        uniq.append(f)
    errors = [f for f in uniq if f["severity"] == "error"]
    warnings = [f for f in uniq if f["severity"] == "warning"]
    complete = not skipped
    return {
        "file": name,
        "syntax": syntax,
        "profile": profile,
        "valid": not errors,
        "complete": complete,
        "errors": errors,
        "warnings": warnings,
        "info": [f for f in uniq if f["severity"] == "info"],
        "layers_run": layers_run,
        "layers_skipped": skipped,
    }


def format_report(res, max_items=60):
    lines = []
    status = "VALID" if res["valid"] else "INVALID"
    if res["valid"] and not res["complete"]:
        status = "NO ERRORS IN THE LAYERS THAT RAN (validation incomplete)"
    lines.append(f"{status}  {res['file']}")
    lines.append(f"  syntax={res['syntax']} profile={res['profile']}")
    lines.append(f"  layers run: {', '.join(res['layers_run']) or '-'}")
    if res["layers_skipped"]:
        lines.append(f"  layers SKIPPED: {', '.join(res['layers_skipped'])}")
    lines.append(f"  {len(res['errors'])} error(s), {len(res['warnings'])} warning(s)")
    for kind in ("errors", "warnings"):
        for f in res[kind][:max_items]:
            lines.append("")
            lines.append(f"[{f['severity'].upper()}] {f['rule']}  ({f['layer']})")
            lines.append(f"  {f['message']}")
            if f["location"]:
                lines.append(f"  at {f['location']}")
            if f["hint"]:
                lines.append(f"  fix: {f['hint']}")
    for f in res["info"]:
        lines.append(f"[INFO] {f['message']}")
    return "\n".join(lines)
